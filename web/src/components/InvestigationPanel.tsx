import { useEffect } from 'react'
import { Beaker, ChevronRight, Sparkles, TerminalSquare } from 'lucide-react'
import { cn } from '../lib/utils'
import { Button, StateMessage } from './cm/primitives'
import { formatEventTime } from './IncidentTimeline'
import { useInvestigate } from '../hooks/useInvestigate'
import type { InvestigationConfidence, TwinIncident } from '../types'

const confidenceStyle: Record<InvestigationConfidence, string> = {
  high: 'text-critical border-critical/40 bg-critical/10',
  medium: 'text-warning border-warning/40 bg-warning/10',
  low: 'text-healthy border-healthy/30 bg-healthy/10',
}

/**
 * Incident investigation report panel.
 * Pass `autoRun` to fire the investigation as soon as an incident is selected
 * (used by the Investigation route; the Incidents route keeps it manual).
 */
export function InvestigationPanel({
  incident,
  autoRun = false,
}: {
  incident: TwinIncident | null
  autoRun?: boolean
}) {
  const { data, isPending, error, mutate, reset } = useInvestigate(incident?.id ?? null)

  useEffect(() => {
    reset()
  }, [incident?.id, reset])

  useEffect(() => {
    if (autoRun && incident && !data && !isPending && !error) {
      mutate()
    }
  }, [autoRun, incident, data, isPending, error, mutate])

  if (!incident) {
    return (
      <StateMessage
        kind="empty"
        title="No incident to investigate"
        detail="Select an incident in the left panel to generate a report."
      />
    )
  }

  const evidenceTitle = new Map(incident.timeline.map((ev) => [ev.id, ev]))

  return (
    <div className="flex min-h-0 flex-1 flex-col">
      {/* Action bar */}
      <div className="flex shrink-0 items-center gap-2 border-b px-3 py-2">
        <Button
          variant="primary"
          onClick={() => mutate()}
          loading={isPending}
          disabled={!incident}
        >
          <Beaker className="size-3.5" />
          {isPending ? 'Investigating…' : data ? 'Re-run investigation' : 'Run investigation'}
        </Button>
        {data && (
          <span
            className={cn(
              'inline-flex items-center gap-1 rounded-sm border px-1.5 py-0.5 font-mono text-[10px] uppercase tracking-wider',
              data.generatedBy === 'gemini'
                ? 'border-primary/30 bg-primary/10 text-primary'
                : 'border-border-strong bg-surface-2 text-muted-foreground',
            )}
            title={
              data.generatedBy === 'gemini'
                ? 'Report generated by the Gemini analysis engine'
                : 'LLM unavailable — deterministic rule-based report'
            }
          >
            <Sparkles className="size-2.5" />
            {data.generatedBy}
          </span>
        )}
      </div>

      {error && (
        <p className="m-3 rounded-md border border-critical/40 bg-critical/10 px-3 py-2 text-xs text-critical">
          {error.message}
        </p>
      )}

      {isPending && <StateMessage kind="loading" title="Investigating incident…" detail="Combining blast radius with the evidence timeline." />}

      {!isPending && !data && !error && (
        <StateMessage
          kind="empty"
          title="Report not generated"
          detail="Run the investigation to get observed facts, hypothesised causes, and next checks."
        />
      )}

      {data && !isPending && (
        <div className="min-h-0 flex-1 space-y-5 overflow-y-auto p-3">
          {/* Summary */}
          <div>
            <p className="label-xs mb-1.5">Summary</p>
            <p className="rounded-md border border-border/60 bg-background px-3 py-3 text-xs leading-relaxed text-foreground">
              {data.summary}
            </p>
          </div>

          {/* Observed facts */}
          <div>
            <p className="label-xs mb-1.5">Observed facts · {data.observedFacts.length}</p>
            <ul className="space-y-1">
              {data.observedFacts.map((fact, i) => (
                <li key={i} className="flex gap-1.5 text-xs leading-relaxed text-foreground">
                  <ChevronRight className="mt-0.5 size-3 shrink-0 text-muted-foreground" />
                  <span>{fact}</span>
                </li>
              ))}
              {data.observedFacts.length === 0 && (
                <li className="text-xs italic text-muted-foreground">No facts extracted.</li>
              )}
            </ul>
          </div>

          {/* Possible causes */}
          <div>
            <p className="label-xs mb-1.5">Possible causes · {data.possibleCauses.length}</p>
            <div className="space-y-1.5">
              {data.possibleCauses.map((c, i) => (
                <div
                  key={i}
                  className="flex items-start justify-between gap-2 rounded-md border border-border/60 bg-background px-2.5 py-2"
                >
                  <p className="min-w-0 text-xs leading-relaxed">{c.cause}</p>
                  <span
                    className={cn(
                      'shrink-0 rounded-sm border px-1.5 py-0.5 font-mono text-[10px] uppercase tracking-wider',
                      confidenceStyle[c.confidence],
                    )}
                  >
                    {c.confidence}
                  </span>
                </div>
              ))}
              {data.possibleCauses.length === 0 && (
                <p className="text-xs italic text-muted-foreground">No hypotheses produced.</p>
              )}
            </div>
          </div>

          {/* Supporting evidence */}
          {data.supportingEvidence.length > 0 && (
            <div>
              <p className="label-xs mb-1.5">Supporting evidence</p>
              <div className="space-y-1">
                {data.supportingEvidence.map((ref) => {
                  const ev = evidenceTitle.get(ref.evidenceId)
                  return (
                    <div
                      key={ref.evidenceId}
                      className="rounded-md border border-border/60 bg-background px-2.5 py-2"
                    >
                      <p className="flex items-baseline gap-2 font-mono text-[10px] text-muted-foreground">
                        <time dateTime={ev?.time}>{ev ? formatEventTime(ev.time) : ref.evidenceId}</time>
                        <span className="truncate text-foreground">{ev?.title ?? ref.evidenceId}</span>
                      </p>
                      <p className="mt-1 text-xs leading-relaxed text-muted-foreground">{ref.note}</p>
                    </div>
                  )
                })}
              </div>
            </div>
          )}

          {/* Next checks */}
          <div>
            <p className="label-xs mb-1.5">Next checks</p>
            <div className="space-y-1">
              {data.nextChecks.map((check, i) => (
                <div
                  key={i}
                  className="flex items-center gap-2 rounded-md border border-border/60 bg-background px-2.5 py-1.5"
                >
                  <TerminalSquare className="size-3 shrink-0 text-primary" />
                  <code className="min-w-0 break-all font-mono text-[10px] leading-relaxed text-foreground">
                    {check}
                  </code>
                </div>
              ))}
              {data.nextChecks.length === 0 && (
                <p className="text-xs italic text-muted-foreground">No follow-up checks suggested.</p>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  )
}
